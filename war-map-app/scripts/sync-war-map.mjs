// Bundles the War Map page into the app.
//   npm run sync-map -- path/to/war-map.html
// Re-run it whenever you update the War Map artifact, then rebuild.
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2] || 'war-map.html';
const html = readFileSync(src, 'utf8');
if (!html.includes("cl.use('db')")) {
  console.error(`${src} doesn't look like the War Map page (no window.claude runtime). Not updated.`);
  process.exit(1);
}
writeFileSync(
  new URL('../src/warMapHtml.js', import.meta.url),
  `// Generated by scripts/sync-war-map.mjs from ${src.split('/').pop()}. Don't edit by hand.\nexport default ${JSON.stringify(html)};\n`,
);
console.log(`Bundled ${src} (${Math.round(html.length / 1024)} KB).`);
